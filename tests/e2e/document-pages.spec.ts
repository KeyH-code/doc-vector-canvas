import { readFile } from 'node:fs/promises'
import { expect, test, type Page } from '@playwright/test'
import { pdfFixture } from '../fixtures/documents/pdfFixture'

const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })

test('文档页切换不污染历史，撤销定位到编辑页，重开保留每页对象', async ({ page }) => {
  await page.goto('/')
  const emptyPage = (id: string, width: number, height: number) => ({ id, width, height, text: null, scene: { id, objects: [] } })
  const source = JSON.stringify({ format: 'document-vector-canvas', version: 3, scene: { id: 'doc', document: {
    source: { kind: 'pdf', data: pdfFixture().toString('base64') }, pages: [emptyPage('p1', 200, 300), emptyPage('p2', 200, 320)],
  } } })
  async function open(buffer: Buffer) {
    const pending = page.waitForEvent('filechooser')
    await button(page, '打开项目').click()
    await (await pending).setFiles({ name: '分页.json', mimeType: 'application/json', buffer })
    await expect(button(page, '第 1 页')).toHaveAttribute('aria-current', 'page')
  }
  await open(Buffer.from(source))
  const host = page.getByTestId('canvas-stage')
  const draw = async (tool: string) => {
    await button(page, tool).click()
    const box = (await host.boundingBox())!
    await page.mouse.move(box.x + 100, box.y + 100); await page.mouse.down()
    await page.mouse.move(box.x + 165, box.y + 150, { steps: 8 }); await page.mouse.up()
  }
  await draw('矩形')
  await expect(page.getByRole('region', { name: '第 1 页对象', exact: true }).getByRole('button', { name: '选中矩形 1' })).toBeVisible()
  await expect(page.getByText('当前画布', { exact: true })).toHaveCount(0)
  await button(page, '第 2 页').click()
  await expect(button(page, '选中矩形 1')).toHaveCount(0)
  await draw('椭圆')
  await button(page, '第 1 页').click()
  await expect(button(page, '隐藏底稿')).toHaveCount(0)
  await button(page, '第 1 页').click({ button: 'right' })
  await page.getByRole('menuitem', { name: '隐藏底稿', exact: true }).click()
  await expect(page.getByRole('menu')).toHaveCount(0)
  await button(page, '撤销').click()
  await expect(button(page, '第 2 页')).toHaveAttribute('aria-current', 'page')
  await expect(button(page, '选中椭圆 1')).toHaveCount(0)
  await button(page, '重做').click()
  await expect(button(page, '选中椭圆 1')).toBeVisible()
  const pending = page.waitForEvent('download')
  await button(page, '保存项目').click()
  const saved = await readFile((await (await pending).path())!)
  const doc = JSON.parse(saved.toString()).scene.document
  expect(doc.pages.map((p: { scene: { objects: { type: string }[] } }) => p.scene.objects[0].type)).toEqual(['rectangle', 'ellipse'])
  await page.reload()
  await open(saved)
  await expect(button(page, '选中矩形 1')).toBeVisible()
  await button(page, '第 1 页').click({ button: 'right' })
  await expect(page.getByRole('menuitem', { name: '隐藏底稿', exact: true })).toBeVisible()
  await expect(button(page, '撤销')).toBeDisabled()
})

test('页目录单列排列，可折叠对象；右键只切换目标页底稿显隐，不切页也不记历史', async ({ page }) => {
  await page.goto('/')
  const pending = page.waitForEvent('filechooser')
  await button(page, '打开项目').click()
  await (await pending).setFiles({ name: '两页.pdf', mimeType: 'application/pdf', buffer: pdfFixture() })
  const first = button(page, '第 1 页'), second = button(page, '第 2 页')
  await expect(first).toHaveAttribute('aria-current', 'page')
  const thumb = first.locator('img')
  await expect(thumb).toBeVisible()
  const [a, b] = await Promise.all([first.boundingBox(), second.boundingBox()])
  expect(a!.x).toBe(b!.x)
  expect(b!.y).toBeGreaterThanOrEqual(a!.y + a!.height)
  const [image, label] = await Promise.all([thumb.boundingBox(), first.getByText('第 1 页', { exact: true }).boundingBox()])
  expect(image!.y).toBeGreaterThanOrEqual(a!.y)
  expect(image!.y + image!.height).toBeLessThanOrEqual(a!.y + a!.height)
  expect(label!.x).toBeGreaterThanOrEqual(image!.x + image!.width)
  expect(label!.y).toBeGreaterThan(image!.y)
  expect(label!.y + label!.height).toBeLessThan(image!.y + image!.height)
  await button(page, '折叠第 1 页对象').click()
  await expect(page.getByRole('region', { name: '第 1 页对象', exact: true })).toBeHidden()
  await button(page, '展开第 1 页对象').click()
  await expect(page.getByRole('region', { name: '第 1 页对象', exact: true })).toBeVisible()

  const pixel = (offset: [number, number]) => page.getByTestId('canvas-stage').locator('canvas[data-fabric="main"]').evaluate((canvas: HTMLCanvasElement, [x, y]) => {
    const cssWidth = canvas.getBoundingClientRect().width
    const zoom = Number(document.querySelector<HTMLSelectElement>('[aria-label="画布缩放"]')!.value)
    const factor = canvas.width / cssWidth * zoom
    return [...canvas.getContext('2d')!.getImageData(canvas.width / 2 + x * factor, canvas.height / 2 + y * factor, 1, 1).data]
  }, offset)
  const pageOnePixel = () => pixel([-80, -130]), pageTwoPixel = () => pixel([-85, -145])
  const white = [255, 255, 255, 255], yellow = [255, 204, 0, 255]
  const menu = page.getByRole('menu')
  const toggle = (name: string) => page.getByRole('menuitem', { name, exact: true })
  await expect.poll(pageOnePixel).toEqual(yellow)
  await first.click({ button: 'right' })
  await toggle('隐藏底稿').click()
  await expect.poll(pageOnePixel).toEqual(white)
  await second.click({ button: 'right' })
  await expect(first).toHaveAttribute('aria-current', 'page')
  await expect(toggle('隐藏底稿')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(menu).toHaveCount(0)
  await expect(second).toBeFocused()
  await second.click({ button: 'right' })
  await page.getByRole('heading', { name: '文档页面' }).click()
  await expect(menu).toHaveCount(0)
  await second.click({ button: 'right' })
  await toggle('隐藏底稿').click()
  await expect(first).toHaveAttribute('aria-current', 'page')
  await expect.poll(pageOnePixel).toEqual(white)
  await second.click()
  await expect(page.getByRole('region', { name: '第 1 页对象', exact: true })).toBeHidden()
  await expect(page.getByRole('region', { name: '第 2 页对象', exact: true })).toBeVisible()
  await expect.poll(pageTwoPixel).toEqual(white)
  await second.press('Shift+F10')
  await expect(toggle('显示底稿')).toBeFocused()
  await page.keyboard.press('Enter')
  await expect.poll(pageTwoPixel).toEqual([0, 153, 51, 255])
  await first.click()
  await expect.poll(pageOnePixel).toEqual(white)
  await first.press('Shift+F10')
  await toggle('显示底稿').click()
  await expect.poll(pageOnePixel).toEqual(yellow)
  await expect(button(page, '撤销')).toBeDisabled()
})
